def validate_shelter_coordinates(record_data: Dict[str, Any]) -> Tuple[bool, Optional[str]]:
    """
    Validates latitude and longitude coordinates for WGS84 range, swapped coords,
    and state bounding constraints.
    """
    lat = record_data.get("latitude")
    lon = record_data.get("longitude")
    state = record_data.get("state", "Uttarakhand")

    if lat is None or lon is None:
        return False, "Missing latitude or longitude coordinates."

    try:
        lat_f = float(lat)
        lon_f = float(lon)
    except (ValueError, TypeError):
        return False, "Non-numeric latitude or longitude."

    # Check for swapped lat/lon (e.g. lat > 40 or lon < 68 in India context)
    if lat_f > 40.0 or lon_f < 68.0:
        return False, f"Swapped or out-of-country coordinates detected: lat={lat_f}, lon={lon_f}."

    # State bounds check if state is registered
    bounds = STATE_GEOGRAPHIC_BOUNDS.get(state)
    if bounds:
        if not (bounds["min_lat"] <= lat_f <= bounds["max_lat"] and bounds["min_lon"] <= lon_f <= bounds["max_lon"]):
            return False, f"Coordinates ({lat_f}, {lon_f}) outside valid geographic bounds for state '{state}'."

    return True, None


def validate_shelter_record(record_data: Dict[str, Any]) -> Tuple[Optional[ShelterRecord], ShelterValidationStatus, Optional[str]]:
    """
    Validates a raw shelter dictionary against geometric bounds, state alignment, and integrity constraints.
    Returns (validated_model, validation_status, error_message).
    """
    s_id = record_data.get("shelter_id") or record_data.get("id")
    if not s_id:
        return None, ShelterValidationStatus.MALFORMED, "Missing required shelter ID."

    valid_coords, coord_err = validate_shelter_coordinates(record_data)
    if not valid_coords:
        return None, ShelterValidationStatus.INVALID_COORDINATES, coord_err

    tot_cap = record_data.get("total_capacity")
    occ = record_data.get("current_occupancy")
    if tot_cap is not None:
        if tot_cap < 0 or (occ is not None and occ < 0):
            return None, ShelterValidationStatus.MALFORMED, "Capacity values cannot be negative."
        avail = max(0, tot_cap - (occ or 0))
        if avail == 0:
            cap_stat = CapacityStatus.FULL
        elif avail <= int(tot_cap * 0.1):
            cap_stat = CapacityStatus.NEAR_CAPACITY
        else:
            cap_stat = CapacityStatus.AVAILABLE
    else:
        avail = None
        cap_stat = CapacityStatus.UNKNOWN

    data_copy = dict(record_data)
    data_copy["shelter_id"] = s_id
    data_copy["id"] = s_id
    data_copy["available_capacity"] = avail
    data_copy["capacity_status"] = cap_stat

    try:
        model = ShelterRecord(**data_copy)
        return model, ShelterValidationStatus.VALID, None
    except Exception as e:
        return None, ShelterValidationStatus.MALFORMED, f"Schema parsing error: {str(e)}"


class ShelterAdapter:
    """
    Shelter Data Adapter for APADA MITRA.
    Maintains validated registry, Haversine geographic filtering, and provenance handling.
    """

    def __init__(self):
        self._raw_data = REGISTERED_SHELTERS_DATA
        self.authority = USDMA_AUTHORITY_NAME
        self.authority_url = USDMA_PORTAL_URL

    def get_all_shelters(self, force_offline: bool = False) -> Tuple[List[ShelterRecord], ShelterDataState]:
        """
        Returns all valid registered shelters with coordinate validation and deduplication.
        """
        valid_shelters: List[ShelterRecord] = []
        seen_ids: Set[str] = set()
        seen_coords: Set[Tuple[float, float]] = set()

        for raw in self._raw_data:
            model, status, err = validate_shelter_record(raw)
            if status == ShelterValidationStatus.VALID and model:
                if model.shelter_id in seen_ids:
                    continue  # Skip duplicate IDs
                coord_pair = (round(model.latitude, 5), round(model.longitude, 5))
                if coord_pair in seen_coords:
                    continue  # Skip duplicate coordinates
                seen_ids.add(model.shelter_id)
                seen_coords.add(coord_pair)
                valid_shelters.append(model)

        return valid_shelters, ShelterDataState.REAL_STATIC_GOVERNMENT

    def get_shelter_by_id(self, shelter_id: str) -> Optional[ShelterRecord]:
        """Looks up a specific shelter by ID."""
        shelters, _ = self.get_all_shelters()
        return next((s for s in shelters if s.shelter_id == shelter_id or s.id == shelter_id), None)

    def get_local_shelter_candidates_for_village(
        self,
        village_id: str,
        village_lat: float,
        village_lon: float,
        radius_km: float = 15.0,
        force_offline: bool = False,
    ) -> List[Tuple[float, ShelterRecord]]:
        """
        Returns shelters strictly within geographic search radius_km for a given village coordinate,
        sorted ascending by Haversine straight-line distance.
        Does NOT expand radius or return distant shelters if count is small.
        """
        shelters, _ = self.get_all_shelters(force_offline=force_offline)
        local_list: List[Tuple[float, ShelterRecord]] = []

        for s in shelters:
            dist = calculate_haversine_distance_km(village_lat, village_lon, s.latitude, s.longitude)
            if dist <= radius_km:
                s_copy = s.model_copy(update={"straight_line_distance_km": dist, "primary_nearby_village_id": village_id})
                local_list.append((dist, s_copy))

        local_list.sort(key=lambda x: x[0])
        return local_list


